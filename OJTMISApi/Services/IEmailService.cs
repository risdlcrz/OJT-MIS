using System.Net;
using System.Net.Mail;
using Microsoft.Extensions.Options;
using Resend;

namespace OJTMISApi.Services
{
    /// <summary>
    /// Settings bound from the "Resend" configuration section.
    /// </summary>
    public sealed class ResendOptions
    {
        public const string SectionName = "Resend";

        /// <summary>Resend API key. Prefer <c>Resend__ApiKey</c> or user-secrets over committing a key.</summary>
        public string ApiKey { get; set; } = string.Empty;

        /// <summary>Verified sender address that Resend is allowed to send from.</summary>
        public string SenderEmail { get; set; } = string.Empty;

        /// <summary>Friendly name shown next to the sender address.</summary>
        public string SenderName { get; set; } = "OJTMIS";

        /// <summary>Front-end base URL used by links inside the built-in templates.</summary>
        public string AppBaseUrl { get; set; } = "http://localhost:5173";
    }

    /// <summary>
    /// A file attached to an outgoing email. Resend expects the bytes and the
    /// MIME type, so PDFs generated by the API can be attached directly.
    /// </summary>
    public sealed class EmailAttachment
    {
        public string FileName { get; init; } = string.Empty;

        public byte[] Content { get; init; } = Array.Empty<byte>();

        /// <summary>MIME type. When omitted it is derived from the file name.</summary>
        public string? ContentType { get; init; }

        /// <summary>Reads a file from disk (for example a generated PDF) into an attachment.</summary>
        public static async Task<EmailAttachment> FromFileAsync(
            string path,
            CancellationToken cancellationToken = default)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(path);

            var content = await File.ReadAllBytesAsync(path, cancellationToken);
            return new EmailAttachment
            {
                FileName = Path.GetFileName(path),
                Content = content
            };
        }
    }

    /// <summary>
    /// Provider-independent description of an email. HtmlBody is sent as the
    /// rich version and TextBody as the plain-text fallback.
    /// </summary>
    public sealed class EmailRequest
    {
        public List<string> To { get; init; } = new();

        public List<string> Cc { get; init; } = new();

        public List<string> Bcc { get; init; } = new();

        public string? ReplyTo { get; init; }

        public string Subject { get; init; } = string.Empty;

        public string? HtmlBody { get; init; }

        public string? TextBody { get; init; }

        public List<EmailAttachment> Attachments { get; init; } = new();

        public Dictionary<string, string>? Headers { get; init; }
    }

    /// <summary>
    /// Global email service used by the API. All mail is delivered through
    /// Resend (HTTPS, bearer token from configuration).
    /// </summary>
    public interface IEmailService
    {
        /// <summary>Sends an arbitrary HTML/plain-text email with optional attachments.</summary>
        /// <returns>The Resend message identifier, or an outbox identifier in local development.</returns>
        Task<string> SendAsync(EmailRequest message, CancellationToken cancellationToken = default);

        /// <summary>Sends the account-creation email containing a temporary password.</summary>
        Task SendTemporaryPasswordAsync(
            string email,
            string name,
            string temporaryPassword,
            CancellationToken cancellationToken = default);

        /// <summary>Sends the password-reset link email.</summary>
        Task SendPasswordResetLinkAsync(
            string email,
            string name,
            string token,
            CancellationToken cancellationToken = default);
    }

    /// <summary>
    /// Sends mail through the Resend API. When no API key is configured the
    /// message is written to App_Data/outbox during development so the flow
    /// still works locally without leaking a production key.
    /// </summary>
    public sealed class ResendEmailService : IEmailService
    {
        /// <summary>Resend rejects payloads above 40 MB; keep a little headroom.</summary>
        private const long MaxAttachmentBytes = 40L * 1024 * 1024;

        private readonly ResendOptions _options;
        private readonly IResend _resend;
        private readonly IWebHostEnvironment _environment;
        private readonly ILogger<ResendEmailService> _logger;

        public ResendEmailService(
            IOptions<ResendOptions> options,
            IResend resend,
            IWebHostEnvironment environment,
            ILogger<ResendEmailService> logger)
        {
            _options = options.Value;
            _resend = resend;
            _environment = environment;
            _logger = logger;
        }

        public async Task<string> SendAsync(EmailRequest message, CancellationToken cancellationToken = default)
        {
            ArgumentNullException.ThrowIfNull(message);
            Validate(message);

            if (!IsConfigured)
            {
                return await WriteOutboxAsync(message, cancellationToken);
            }

            if (string.IsNullOrWhiteSpace(_options.SenderEmail))
            {
                throw new InvalidOperationException(
                    "Resend is configured but Resend:SenderEmail is empty. Set a verified sender address.");
            }

            var payload = new Resend.EmailMessage
            {
                From = new EmailAddress
                {
                    Email = _options.SenderEmail.Trim(),
                    DisplayName = string.IsNullOrWhiteSpace(_options.SenderName)
                        ? null
                        : _options.SenderName.Trim()
                },
                Subject = message.Subject,
                HtmlBody = message.HtmlBody,
                TextBody = message.TextBody,
                Headers = message.Headers
            };

            AddRecipients(payload.To, message.To);

            if (message.Cc.Count > 0)
            {
                payload.Cc = new EmailAddressList();
                AddRecipients(payload.Cc, message.Cc);
            }

            if (message.Bcc.Count > 0)
            {
                payload.Bcc = new EmailAddressList();
                AddRecipients(payload.Bcc, message.Bcc);
            }

            if (!string.IsNullOrWhiteSpace(message.ReplyTo))
            {
                payload.ReplyTo = message.ReplyTo.Trim();
            }

            if (message.Attachments.Count > 0)
            {
                payload.Attachments = message.Attachments.Select(attachment => new Resend.EmailAttachment
                {
                    Filename = attachment.FileName,
                    Content = attachment.Content,
                    ContentType = attachment.ContentType ?? GetContentType(attachment.FileName)
                }).ToList();
            }

            var recipients = string.Join(", ", message.To);

            try
            {
                var response = await _resend.EmailSendAsync(payload, cancellationToken);

                if (!response.Success)
                {
                    var error = response.Exception;
                    throw new InvalidOperationException(
                        $"Resend rejected the email: {error?.Message ?? "unknown error"}",
                        error);
                }

                var messageId = response.Content.ToString();
                _logger.LogInformation(
                    "Sent \"{Subject}\" to {Recipients} through Resend ({MessageId}).",
                    message.Subject,
                    recipients,
                    messageId);

                return messageId;
            }
            catch (ResendException ex)
            {
                _logger.LogError(
                    ex,
                    "Resend could not deliver \"{Subject}\" to {Recipients}.",
                    message.Subject,
                    recipients);

                var status = ex.StatusCode is { } code ? ((int)code).ToString() : "unknown";
                throw new InvalidOperationException(
                    $"Resend could not deliver the email (status {status}). {ex.Message}",
                    ex);
            }
        }

        public Task SendTemporaryPasswordAsync(
            string email,
            string name,
            string temporaryPassword,
            CancellationToken cancellationToken = default)
        {
            var appBaseUrl = AppBaseUrl();
            var greeting = string.IsNullOrWhiteSpace(name) ? "Hello" : $"Hello {name}";
            var signIn = $"{appBaseUrl}/login.html";

            var textBody =
                $"{greeting},\r\n\r\n" +
                "An OJT-MIS account was created for this email address.\r\n\r\n" +
                $"Sign in at {signIn}\r\n" +
                $"Temporary password: {temporaryPassword}\r\n\r\n" +
                "After you sign in, change this password from Account > Security.\r\n";

            return SendAsync(new EmailRequest
            {
                To = new List<string> { email },
                Subject = "Your OJT-MIS temporary password",
                HtmlBody = EmailTemplates.TemporaryPassword(appBaseUrl, name, temporaryPassword),
                TextBody = textBody
            }, cancellationToken);
        }

        public Task SendPasswordResetLinkAsync(
            string email,
            string name,
            string token,
            CancellationToken cancellationToken = default)
        {
            var appBaseUrl = AppBaseUrl();
            var greeting = string.IsNullOrWhiteSpace(name) ? "Hello" : $"Hello {name}";
            var link = BuildResetLink(appBaseUrl, email, token);

            var textBody =
                $"{greeting},\r\n\r\n" +
                "A password reset was requested for your OJT-MIS account.\r\n\r\n" +
                $"Reset your password: {link}\r\n\r\n" +
                "If you did not request this, you can ignore this message. The link expires with the reset token.\r\n";

            return SendAsync(new EmailRequest
            {
                To = new List<string> { email },
                Subject = "Reset your OJT-MIS password",
                HtmlBody = EmailTemplates.PasswordReset(name, link),
                TextBody = textBody
            }, cancellationToken);
        }

        private string AppBaseUrl() =>
            string.IsNullOrWhiteSpace(_options.AppBaseUrl)
                ? "http://localhost:5173"
                : _options.AppBaseUrl.TrimEnd('/');

        private static string BuildResetLink(string appBaseUrl, string email, string token) =>
            $"{appBaseUrl}/login.html?mode=reset&email={Uri.EscapeDataString(email)}&token={Uri.EscapeDataString(token)}";

        private bool IsConfigured
        {
            get
            {
                var apiKey = ResolveApiKey();
                return !string.IsNullOrWhiteSpace(apiKey) &&
                       !apiKey.StartsWith("re_your_api_key", StringComparison.OrdinalIgnoreCase);
            }
        }

        private string? ResolveApiKey()
        {
            if (!string.IsNullOrWhiteSpace(_options.ApiKey))
            {
                return _options.ApiKey.Trim();
            }

            var fromEnvironment = Environment.GetEnvironmentVariable("RESEND_API_KEY");
            return string.IsNullOrWhiteSpace(fromEnvironment) ? null : fromEnvironment.Trim();
        }

        private static void AddRecipients(EmailAddressList list, IEnumerable<string> addresses)
        {
            foreach (var address in addresses)
            {
                list.Add(address.Trim());
            }
        }

        private static void Validate(EmailRequest message)
        {
            if (message.To.Count == 0)
            {
                throw new ArgumentException("At least one recipient is required.", nameof(message));
            }

            foreach (var address in message.To.Concat(message.Cc).Concat(message.Bcc))
            {
                if (!MailAddress.TryCreate(address, out _))
                {
                    throw new ArgumentException($"'{address}' is not a valid email address.", nameof(message));
                }
            }

            if (string.IsNullOrWhiteSpace(message.Subject))
            {
                throw new ArgumentException("A subject is required.", nameof(message));
            }

            if (string.IsNullOrWhiteSpace(message.HtmlBody) && string.IsNullOrWhiteSpace(message.TextBody))
            {
                throw new ArgumentException("An HTML or plain-text body is required.", nameof(message));
            }

            long totalBytes = 0;
            foreach (var attachment in message.Attachments)
            {
                if (string.IsNullOrWhiteSpace(attachment.FileName) ||
                    Path.GetFileName(attachment.FileName) != attachment.FileName)
                {
                    throw new ArgumentException(
                        "Each attachment needs a plain file name without a directory.",
                        nameof(message));
                }

                if (attachment.Content.Length == 0)
                {
                    throw new ArgumentException(
                        $"Attachment '{attachment.FileName}' is empty.",
                        nameof(message));
                }

                totalBytes += attachment.Content.LongLength;
            }

            if (totalBytes > MaxAttachmentBytes)
            {
                throw new ArgumentException(
                    $"Attachments total {totalBytes / (1024 * 1024)} MB; Resend accepts at most 40 MB.",
                    nameof(message));
            }
        }

        private static string GetContentType(string fileName) =>
            Path.GetExtension(fileName).ToLowerInvariant() switch
            {
                ".pdf" => "application/pdf",
                ".png" => "image/png",
                ".jpg" or ".jpeg" => "image/jpeg",
                ".gif" => "image/gif",
                ".webp" => "image/webp",
                ".csv" => "text/csv",
                ".txt" => "text/plain",
                ".doc" => "application/msword",
                ".docx" => "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                ".xls" => "application/vnd.ms-excel",
                ".xlsx" => "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                ".zip" => "application/zip",
                _ => "application/octet-stream"
            };

        private async Task<string> WriteOutboxAsync(EmailRequest message, CancellationToken cancellationToken)
        {
            if (!_environment.IsDevelopment())
            {
                throw new InvalidOperationException(
                    "Resend is not configured. Set Resend:ApiKey (or the RESEND_API_KEY environment variable).");
            }

            var folder = Path.Combine(_environment.ContentRootPath, "App_Data", "outbox");
            Directory.CreateDirectory(folder);

            var baseName = $"{DateTime.Now:yyyyMMddHHmmssfff}-{Guid.NewGuid():N}";
            var html = message.HtmlBody ?? $"<pre>{WebUtility.HtmlEncode(message.TextBody)}</pre>";
            var file = Path.Combine(folder, baseName + ".html");

            var header =
                $"<!-- To: {WebUtility.HtmlEncode(string.Join(", ", message.To))} -->\r\n" +
                $"<!-- Subject: {WebUtility.HtmlEncode(message.Subject)} -->\r\n";

            await File.WriteAllTextAsync(file, header + html, cancellationToken);

            foreach (var attachment in message.Attachments)
            {
                var attachmentPath = Path.Combine(folder, $"{baseName}-{attachment.FileName}");
                await File.WriteAllBytesAsync(attachmentPath, attachment.Content, cancellationToken);
            }

            _logger.LogWarning(
                "Resend is not configured. Wrote \"{Subject}\" for {Recipients} to {File}.",
                message.Subject,
                string.Join(", ", message.To),
                file);

            return $"outbox:{baseName}";
        }
    }

    /// <summary>Inline HTML templates used by the built-in account emails.</summary>
    internal static class EmailTemplates
    {
        public static string TemporaryPassword(string appBaseUrl, string name, string temporaryPassword)
        {
            var greeting = string.IsNullOrWhiteSpace(name)
                ? "Hello"
                : $"Hello {WebUtility.HtmlEncode(name)}";
            var signIn = WebUtility.HtmlEncode($"{appBaseUrl}/login.html");
            var password = WebUtility.HtmlEncode(temporaryPassword);

            var content = $"""
                <p style="margin:0 0 16px">{greeting},</p>
                <p style="margin:0 0 16px">An OJT-MIS account was created for this email address.</p>
                <p style="margin:0 0 24px">
                  <a href="{signIn}" style="display:inline-block;background:#2563eb;color:#ffffff;text-decoration:none;padding:12px 20px;border-radius:6px;font-weight:600">Sign in to OJT-MIS</a>
                </p>
                <p style="margin:0 0 8px;color:#6b7280;font-size:13px;text-transform:uppercase;letter-spacing:.04em">Temporary password</p>
                <p style="margin:0 0 24px;padding:12px 16px;background:#f3f4f6;border-radius:6px;font-family:Consolas,Menlo,monospace;font-size:16px">{password}</p>
                <p style="margin:0;color:#4b5563">After you sign in, change this password from Account &gt; Security.</p>
                """;

            return Layout("Your OJT-MIS temporary password", content);
        }

        public static string PasswordReset(string name, string resetLink)
        {
            var greeting = string.IsNullOrWhiteSpace(name)
                ? "Hello"
                : $"Hello {WebUtility.HtmlEncode(name)}";
            var link = WebUtility.HtmlEncode(resetLink);

            var content = $"""
                <p style="margin:0 0 16px">{greeting},</p>
                <p style="margin:0 0 24px">A password reset was requested for your OJT-MIS account.</p>
                <p style="margin:0 0 24px">
                  <a href="{link}" style="display:inline-block;background:#2563eb;color:#ffffff;text-decoration:none;padding:12px 20px;border-radius:6px;font-weight:600">Reset your password</a>
                </p>
                <p style="margin:0;color:#4b5563">If you did not request this, you can ignore this message. The link expires with the reset token.</p>
                """;

            return Layout("Reset your OJT-MIS password", content);
        }

